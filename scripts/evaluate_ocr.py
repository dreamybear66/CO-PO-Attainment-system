"""Measure answer-sheet OCR on synthetic scans and write docs/ocr-evaluation.md.

  python -m scripts.evaluate_ocr [--sheets 40] [--seeds 3]

For each scan condition, builds `seeds` PDFs of `sheets` cover pages (datagen/ocr_samples.py,
handwriting from MNIST's held-out digits), reads them as the API does and compares with the
answer key. No database is needed. The number that matters most is "wrong and not flagged": a
wrong value the review screen would not highlight.
"""

import argparse
import tempfile
import time
from pathlib import Path

import numpy as np

from api import config
from api.ocr import reader
from api.ocr.digits import load_mnist
from datagen.ocr_samples import STEMS, Paper, Question, build_pdf, random_key

CONDITIONS = [  # name, roughness, JPEG quality
    ("Normal scan", 1.0, 80),
    ("Rough scan (2x skew and grain, JPEG 60)", 2.0, 60),
]
QUESTIONS = [Question("Q1", 10, [1], 2, STEMS[0]), Question("Q2", 10, [2], 3, STEMS[1]),
             Question("Q3", 15, [2, 3], 3, STEMS[2]), Question("Q4", 15, [4], 4, STEMS[3]),
             Question("Q5", 5, [5], 1, STEMS[4]), Question("Q6", 5, [1, 6], 5, STEMS[5])]


def run(sheets: int, seed: int, rough: float, quality: int, mnist, workdir: Path) -> dict:
    paper = Paper("IS243", "Database Management Systems", "CIE Test 1", 60, QUESTIONS)
    usns = [f"1RV24IS{i:03d}" for i in range(1, sheets + 6)]          # 5 enrolled without a sheet
    rng = np.random.default_rng(seed)
    key = random_key(paper, usns[:sheets], rng, absent_share=0)
    pdf = build_pdf(key, workdir / f"s{seed}-{rough}.pdf", seed=seed, digits=mnist[0], labels=mnist[1],
                    rough=rough, jpeg_quality=quality)
    data = pdf.read_bytes()
    t = time.perf_counter()
    raw = reader.read_pdf(data, n_questions=len(QUESTIONS))
    review = reader.review(raw, [{"q_no": q.q_no, "max_marks": q.max_marks} for q in QUESTIONS],
                           usns, reader.DEFAULT_REVIEW_CONFIDENCE)
    seconds = time.perf_counter() - t
    got = [(q["q_no"], q["max_marks"], q["cos"], q["bloom"]) for q in raw["paper"]["questions"]]
    want = [(q.q_no, q.max_marks, q.cos, q.bloom) for q in QUESTIONS]
    out = {"paper_exact": got == want, "marks": 0, "marks_right": 0, "usn_right": 0, "sheets": len(key.sheets),
           "flagged_sheets": 0, "flagged_values": 0, "wrong_flagged": 0, "wrong_unflagged": 0,
           "absent_right": set(review["absent"]) == set(usns[sheets:]), "seconds": seconds,
           "pages": len(key.sheets) + 1, "mb": len(data) / 1e6}
    for s, truth in zip(review["sheets"], key.sheets):
        out["flagged_sheets"] += s["check"]
        right_usn = s["usn"] == truth.usn
        out["usn_right"] += right_usn
        if not right_usn:
            out["wrong_flagged" if s["check"] else "wrong_unflagged"] += 1
        for m in s["marks"]:
            out["marks"] += 1
            out["flagged_values"] += m["check"]
            if m["value"] == truth.marks[m["q_no"]]:
                out["marks_right"] += 1
            else:
                out["wrong_flagged" if (m["check"] or s["check"]) else "wrong_unflagged"] += 1
    return out


def pct(a, b):
    return f"{100 * a / b:.1f}%" if b else "—"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--sheets", type=int, default=40)
    p.add_argument("--seeds", type=int, default=3)
    args = p.parse_args()
    mnist = load_mnist()
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        for name, rough, quality in CONDITIONS:
            runs = [run(args.sheets, 100 + s, rough, quality, mnist, Path(tmp)) for s in range(args.seeds)]
            tot = {k: sum(r[k] for r in runs) for k in runs[0] if k not in ("paper_exact", "absent_right")}
            rows.append((name, runs, tot))
            print(name, tot)

    lines = [
        "# Answer-sheet OCR evaluation",
        "",
        f"Generated by `python -m scripts.evaluate_ocr` ({args.seeds} PDFs per condition, {args.sheets} cover "
        f"pages each, 6 questions per sheet, 5 enrolled students without a sheet). Synthetic scans from "
        "`datagen/ocr_samples.py`: printed question paper, marks handwritten with MNIST's 10,000 held-out "
        "digits (never seen in training). Review threshold: "
        f"{reader.DEFAULT_REVIEW_CONFIDENCE:.2f}.",
        "",
        "| Condition | Question papers read exactly | Marks right | USNs right | Absent list right | "
        "Sheets flagged | Wrong and flagged | Wrong and **not** flagged | Seconds per page | MB per page |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for name, runs, t in rows:
        lines.append(
            f"| {name} | {sum(r['paper_exact'] for r in runs)} of {len(runs)} | {pct(t['marks_right'], t['marks'])} "
            f"({t['marks_right']}/{t['marks']}) | {pct(t['usn_right'], t['sheets'])} | "
            f"{sum(r['absent_right'] for r in runs)} of {len(runs)} | {pct(t['flagged_sheets'], t['sheets'])} | "
            f"{t['wrong_flagged']} | {t['wrong_unflagged']} | {t['seconds'] / t['pages']:.2f} | {t['mb'] / t['pages']:.2f} |")
    lines += [
        "",
        "## Reading the table",
        "",
        "- **Wrong and not flagged** is what a teacher could save without noticing; every other error is",
        "  highlighted on the review screen. A sheet is flagged when any of its values is below the threshold,",
        "  its USN is unclear or shared, or the total written on it is not the sum of its marks.",
        "- Marks are chosen from 0 to the question's maximum and USNs among the enrolled students, so a",
        "  digit misread into an impossible value cannot be suggested.",
        "- These are synthetic scans of a synthetic layout. The acceptance target is still an open question",
        "  (PRD Section 10); real answer sheets will need their own measurement.",
    ]
    out = config.ROOT / "docs" / "ocr-evaluation.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
