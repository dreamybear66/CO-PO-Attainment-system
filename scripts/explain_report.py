"""PRD Section 8 'Performance' (NFR-7): EXPLAIN ANALYZE with and without the 006 indexes.

Runs on the main database (load data with datagen first). The "without" condition drops the 006
indexes inside a transaction that is rolled back, so the database is left unchanged. The two
conditions are measured in alternating rounds so cache warm-up does not favour either one.
Writes docs/explain/report.md.

Usage:  python -m scripts.explain_report [--offering 200] [--rounds 3] [--runs 5]
"""

import argparse
import statistics
import time

import psycopg

from api import config

INDEXES = [
    "student_question_mark_question_idx", "question_co_map_co_idx",
    "assessment_offering_idx", "assessment_question_assessment_idx", "course_offering_course_idx",
    "course_offering_faculty_idx", "co_attainment_co_idx", "enrollment_usn_idx",
]

# The aggregation inside fn_student_co_score, written out so EXPLAIN can see into it.
AGGREGATION = """
SELECT s.usn, s.co_id, sum(w.weight_pct * s.pct) / sum(w.weight_pct) AS pct
FROM student_component_co_pct s
JOIN config_component_weight w ON w.config_id = %(config)s AND w.component = s.component
WHERE s.offering_id = %(offering)s
GROUP BY s.usn, s.co_id
"""

# Root-cause access path: every student's score on one CO across all its offerings.
BY_CO = "SELECT usn, offering_id, pct FROM student_co_score WHERE co_id = %(co)s"

OPERATIONS = [
    ("Scores for one CO across all offerings (root-cause path)", BY_CO, "runs"),
    ("CO aggregation, one offering", AGGREGATION, "runs"),
    ("sp_compute_attainment, one offering", "CALL sp_compute_attainment(%(offering)s, p_refresh => false)", "runs"),
    ("sp_compute_all, whole programme", "CALL sp_compute_all()", 1),
]


def sample(conn, sql, params, runs) -> list[float]:
    out = []
    for _ in range(runs):
        started = time.perf_counter()
        conn.execute(sql, params)
        out.append((time.perf_counter() - started) * 1000)
    return out


def plan(conn, params) -> str:
    return "\n".join(r[0] for r in conn.execute("EXPLAIN (ANALYZE, BUFFERS, COSTS OFF) " + BY_CO, params))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--offering", type=int, default=200)
    parser.add_argument("--rounds", type=int, default=3)
    parser.add_argument("--runs", type=int, default=5)
    args = parser.parse_args()

    with psycopg.connect(config.owner_dsn()) as conn:
        marks = conn.execute("SELECT count(*) FROM student_question_mark").fetchone()[0]
        params = {
            "offering": args.offering,
            "config": conn.execute("SELECT config_id FROM v_offering_config WHERE offering_id = %s",
                                   (args.offering,)).fetchone()[0],
            "co": conn.execute("SELECT co_id FROM course_outcome co JOIN course c USING (course_id) "
                               "WHERE c.code = 'IS231' AND co.co_number = 2").fetchone()[0],
        }
        conn.execute("ANALYZE")
        conn.commit()

        samples = {cond: {label: [] for label, *_ in OPERATIONS} for cond in ("without", "with")}
        plans = {}
        for _ in range(args.rounds):
            for cond in ("with", "without"):
                if cond == "without":
                    for name in INDEXES:
                        conn.execute(f"DROP INDEX {name}")
                    conn.execute("ANALYZE")
                for label, sql, runs in OPERATIONS:
                    n = args.runs if runs == "runs" else runs
                    samples[cond][label] += sample(conn, sql, params, n)
                plans[cond] = plan(conn, params)
                conn.rollback()

    out = config.ROOT / "docs" / "explain" / "report.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Index performance report",
        "",
        f"PostgreSQL 16, {marks:,} rows in `student_question_mark`, offering {args.offering}. "
        f"Median over {args.rounds} alternating rounds ({args.runs} runs each; programme run: 1 per round). "
        "Generated by `python -m scripts.explain_report`.",
        "",
        "| Operation | Without 006 indexes (ms) | With indexes (ms) | Speed-up |",
        "| --- | ---: | ---: | ---: |",
    ]
    for label, *_ in OPERATIONS:
        b, a = statistics.median(samples["without"][label]), statistics.median(samples["with"][label])
        lines.append(f"| {label} | {b:,.1f} | {a:,.1f} | {b / a:,.1f}x |")
    lines += [
        "",
        "The per-offering computation reads marks through constraint indexes that exist either way "
        "(`enrollment` UNIQUE `(offering_id, usn)` and the `student_question_mark` primary key), so its "
        "plan is the same with or without 006. The 006 indexes serve access by CO across offerings — "
        "root-cause analysis and trends — which otherwise scans every mark.",
    ]
    for title, key in (("Without indexes", "without"), ("With indexes", "with")):
        lines += ["", f"## Plan (scores for one CO): {title}", "", "```", plans[key], "```"]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[: 6 + len(OPERATIONS)]))


if __name__ == "__main__":
    main()
