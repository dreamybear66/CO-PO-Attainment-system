"""Replay early warning on finished offerings and write docs/early-warning-evaluation.md.

  python -m scripts.evaluate_early_warning [--database copo] [--year 2025-26]

For every finished offering of the test year, pretend the term has only reached a stage (CIE Test 1;
then CIE Test 1 + Quiz 1; then both tests and both quizzes), predict from the earlier years exactly
as the app does, and compare with what happened: did the student end below the CO's target?
Needs the demo database (python -m scripts.demo).
"""

import argparse

import numpy as np
import psycopg
from psycopg.rows import dict_row
from sklearn.metrics import roc_auc_score

from api import config
from api.services import early_warning

CUTS = (0.3, 0.4, 0.5, 0.6)
STAGES = [
    ("After CIE Test 1", [("CIE_THEORY", 1)]),
    ("After CIE Test 1 and Quiz 1", [("CIE_THEORY", 1), ("CIE_QUIZ", 1)]),
    ("After both CIE tests and quizzes", [("CIE_THEORY", 1), ("CIE_QUIZ", 1), ("CIE_THEORY", 2), ("CIE_QUIZ", 2)]),
]


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--database", default=None)
    p.add_argument("--year", default="2025-26")
    args = p.parse_args()
    with psycopg.connect(config.owner_dsn(args.database), row_factory=dict_row) as pg:
        flag_prob = float(pg.execute("SELECT max(ew_flag_prob) AS f FROM attainment_config").fetchone()["f"])
        offerings = [r["offering_id"] for r in pg.execute("""
            SELECT o.offering_id FROM course_offering o WHERE o.academic_year = %s
              AND EXISTS (SELECT 1 FROM assessment a WHERE a.offering_id = o.offering_id)
              AND NOT EXISTS (SELECT 1 FROM assessment a WHERE a.offering_id = o.offering_id AND NOT a.locked)
            ORDER BY o.offering_id""", (args.year,))]
        truth = {(r["offering_id"], r["usn"], r["co_id"]): r["missed"] for r in pg.execute("""
            SELECT s.offering_id, s.usn, s.co_id, (s.pct < ac.target_pct) AS missed
            FROM student_co_score s JOIN v_offering_config oc USING (offering_id) JOIN attainment_config ac USING (config_id)
            WHERE s.offering_id = ANY(%s)""", (offerings,))}
        rows = []
        for name, keys in STAGES:
            y, p_hat, skipped = [], [], 0
            for oid in offerings:
                try:
                    r = early_warning.predict(pg, oid, keys)
                except early_warning.EarlyWarningError:
                    skipped += 1
                    continue
                for x in r["predictions"]:
                    t = truth.get((oid, x["usn"], x["co_id"]))
                    if t is not None:
                        y.append(1 if t else 0)
                        p_hat.append(x["probability"])
            y, p_hat = np.array(y), np.array(p_hat)
            flag = p_hat >= flag_prob
            tp = int((flag & (y == 1)).sum())
            cuts = {}
            for cut in CUTS:
                f = p_hat >= cut
                hit = int((f & (y == 1)).sum())
                cuts[cut] = (hit / max(int(y.sum()), 1), hit / max(int(f.sum()), 1), int(f.sum()))
            rows.append({"stage": name, "offerings": len(offerings) - skipped, "pairs": len(y), "cuts": cuts,
                         "missed": int(y.sum()), "flagged": int(flag.sum()),
                         "recall": tp / max(int(y.sum()), 1), "precision": tp / max(int(flag.sum()), 1),
                         "auc": roc_auc_score(y, p_hat) if len(set(y)) == 2 else float("nan")})
            print(rows[-1])

    lines = [
        "# Early-warning evaluation",
        "",
        f"Generated by `python -m scripts.evaluate_early_warning` on the demo data. Every finished offering of "
        f"{args.year} is replayed as if the term had only reached a stage, predicted from earlier years as the app "
        f"does, and compared with the end of term: did the student finish below the CO's target? Flag cut-off "
        f"`ew_flag_prob` = {flag_prob:.2f}.",
        "",
        "| Stage | Offerings | Student-CO pairs | Missed the CO | Flagged | Missed and flagged (recall) | "
        "Flagged and missed (precision) | AUC |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for r in rows:
        lines.append(f"| {r['stage']} | {r['offerings']} | {r['pairs']:,} | {r['missed']:,} | {r['flagged']:,} | "
                     f"{100 * r['recall']:.1f}% | {100 * r['precision']:.1f}% | {r['auc']:.3f} |")
    lines += [
        "",
        "## Choosing the cut-off",
        "",
        "Recall / precision (students flagged) at other values of `ew_flag_prob`:",
        "",
        "| Stage | " + " | ".join(f"{c:.1f}" for c in CUTS) + " |",
        "| --- | " + " | ".join("---:" for _ in CUTS) + " |",
    ]
    for r in rows:
        lines.append(f"| {r['stage']} | " + " | ".join(
            f"{100 * rc:.0f}% / {100 * pr:.0f}% ({n:,})" for rc, pr, n in (r["cuts"][c] for c in CUTS)) + " |")
    lines += [
        "",
        "## Reading the table",
        "",
        "- **Recall**: of the students who did end below target in a CO, the share the warning had flagged.",
        "  **Precision**: of the flags, the share that were right. AUC 0.5 is chance, 1.0 perfect ranking.",
        "- A lower cut-off flags more students (higher recall, lower precision); it is a rule-version setting.",
        "- The demo marks are synthetic: each student has a hidden skill per CO, so these numbers show the",
        "  method works, not how well it would do on a real class. The acceptance target is still an open",
        "  question (PRD Section 10).",
    ]
    out = config.ROOT / "docs" / "early-warning-evaluation.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
