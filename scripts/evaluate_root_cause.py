"""Root-cause evaluation (PRD Section 11.6): detection, false positives and sensitivity.

Builds datagen/scenario.py datasets in a scratch database (default copo_test, which it migrates
first and empties) across sample sizes, effect strengths and noise levels, runs fn_root_cause on
each, and checks the planted story on the main synthetic dataset (read only). Writes
docs/root-cause-evaluation.md.

Usage:  python -m scripts.evaluate_root_cause [--seeds 10] [--database copo_test] [--dataset copo]
"""

import argparse
import statistics

import psycopg
from psycopg.rows import dict_row

from api import config
from datagen import scenario as sc
from scripts import migrate
from scripts.migrate import truncate_all

TEST_DB = "copo_test"


def thresholds(conn) -> str:
    """The scenario's rule version, as the report header states it."""
    c = conn.execute("SELECT rc_min_n, rc_min_r, rc_max_depth, rc_depth_decay FROM attainment_config "
                     "WHERE config_id = 1").fetchone()
    return (f"n ≥ {c['rc_min_n']}, r ≥ {c['rc_min_r']}, depth ≤ {c['rc_max_depth']}, "
            f"decay {c['rc_depth_decay']} per extra level")


def trial(conn, **kw) -> dict:
    truncate_all(conn)
    sc.build(conn, **kw)
    rows = {r["up_co_id"]: r for r in conn.execute("SELECT * FROM fn_root_cause(%s, %s)", (sc.DN_OFFERING, sc.WEAK))}
    return {
        "cause_first": rows[sc.CAUSE]["likely_cause_rank"] == 1,
        "decoy_passes": bool(rows[sc.DECOY]["passes"]),
        "any_passes": any(r["passes"] for r in rows.values()),
        "r_cause": float(rows[sc.CAUSE]["correlation"] or 0),
    }


def pct(xs) -> str:
    return f"{100 * sum(xs) / len(xs):.0f}%"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seeds", type=int, default=10)
    parser.add_argument("--database", default=TEST_DB, help="scratch database for the scenarios (emptied)")
    parser.add_argument("--dataset", default=config.PG_DATABASE, help="database with the main synthetic dataset")
    args = parser.parse_args()
    seeds = range(1, args.seeds + 1)
    migrate.apply(args.database, reset=True)        # a fresh schema: the scratch database is emptied anyway

    with psycopg.connect(config.owner_dsn(args.database), autocommit=True, row_factory=dict_row) as conn:
        trial(conn, n=20, seed=1)
        lines = ["# Root-cause evaluation", "",
                 "Generated by `python -m scripts.evaluate_root_cause` "
                 f"({args.seeds} seeds per cell). Thresholds: {thresholds(conn)}. "
                 "Scenario: `datagen/scenario.py` (planted cause UP101 CO2, decoy UP101 CO5).", ""]
        lines += ["## Detection: planted cause ranked first (decoy passing in brackets)", "",
                  "| Students | effect 0.4 | effect 0.6 | effect 0.8 |", "| ---: | ---: | ---: | ---: |"]
        for n in (20, 40, 60, 120):
            cells = []
            for effect in (0.4, 0.6, 0.8):
                runs = [trial(conn, n=n, effect=effect, noise=0.5, seed=s) for s in seeds]
                cells.append(f"{pct([r['cause_first'] for r in runs])} ({pct([r['decoy_passes'] for r in runs])})")
            lines.append(f"| {n} | " + " | ".join(cells) + " |")
            print(lines[-1])

        lines += ["", "## False positives: random data (effect 0), runs where any candidate passes", "",
                  "| Students | Runs with a spurious cause |", "| ---: | ---: |"]
        for n in (20, 40, 60, 120):
            runs = [trial(conn, n=n, effect=0.0, noise=0.5, seed=100 + s) for s in range(2 * args.seeds)]
            lines.append(f"| {n} | {pct([r['any_passes'] for r in runs])} of {len(runs)} |")
            print(lines[-1])

        lines += ["", "## Sensitivity to noise (60 students, effect 0.8)", "",
                  "| Mark noise (logit sd) | Mean r of planted cause | Ranked first |", "| ---: | ---: | ---: |"]
        for noise in (0.25, 0.5, 1.0, 2.0):
            runs = [trial(conn, n=60, effect=0.8, noise=noise, seed=200 + s) for s in seeds]
            lines.append(f"| {noise} | {statistics.mean(r['r_cause'] for r in runs):.2f} | {pct([r['cause_first'] for r in runs])} |")
            print(lines[-1])

    with psycopg.connect(config.owner_dsn(args.dataset), row_factory=dict_row) as conn:
        lines += ["", "## Main synthetic dataset: DBMS CO4, planted year 2024-25", "",
                  "| Section | DBMS CO4 final | Candidate | r | n | Passes | Rank |",
                  "| --- | ---: | --- | ---: | ---: | --- | ---: |"]
        offerings = conn.execute("""
            SELECT o.offering_id, o.section, co.co_id, ca.final_level
            FROM course_offering o JOIN course c USING (course_id)
            JOIN course_outcome co ON co.course_id = c.course_id AND co.co_number = 4
            JOIN co_attainment ca ON ca.offering_id = o.offering_id AND ca.co_id = co.co_id
            WHERE c.code = 'IS243' AND o.academic_year = '2024-25' ORDER BY o.section""").fetchall()
        for o in offerings:
            for r in conn.execute("SELECT * FROM fn_root_cause(%s, %s)", (o["offering_id"], o["co_id"])):
                lines.append(f"| {o['section']} | {o['final_level']} | {r['up_course_code']} CO{r['up_co_number']} "
                             f"(depth {r['depth']}) | {r['correlation']} | {r['n']} | {'yes' if r['passes'] else 'no'} "
                             f"| {r['likely_cause_rank'] or ''} |")

    out = config.ROOT / "docs" / "root-cause-evaluation.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
